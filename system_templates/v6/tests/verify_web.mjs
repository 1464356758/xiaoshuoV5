import assert from 'node:assert/strict';
import {readFile,writeFile} from 'node:fs/promises';
import {pathToFileURL} from 'node:url';
import path from 'node:path';
const [release,fixture,legacy]=process.argv.slice(2);
const uri=n=>pathToFileURL(path.join(release,'web',n)).href;
const core=await import(uri('hub-core.mjs'));
const {validateManifest}=await import(uri('core.mjs'));
const v6=await import(uri('v6-reader.mjs'));
const rootURL='https://github.com/example/synthetic-novel';
function client(root,url=rootURL){return {repo:core.parseRepository(url),snapshot:async()=>({commit:'a'.repeat(40),branch:'main'}),async readFile(p){const text=await readFile(path.join(root,p),'utf8');return {text,hash:await core.sha256(text)};},async readJSON(p){const r=await this.readFile(p);return {...r,data:JSON.parse(r.text)};},async optionalJSON(p){try{return await this.readJSON(p)}catch(e){if(e.code==='ENOENT')return null;throw e;}}};}
const c=client(fixture),book=await core.loadBook(c);
assert.equal(book.state.schema,'novel-v6');
assert.equal((await core.inspectExecution({repository_url:rootURL,book_id:book.state.book_id},{client:c})).status,'completed');
assert.ok(await core.readFormalChapter(c,book,book.manifest.chapters[0]));
const old=await core.loadBook(client(legacy,'https://github.com/1464356758/XS1'));
assert.equal(old.manifest.book.id,'d9169807-b382-402b-b7d0-8e9c84d46670');
assert.ok(await core.readFormalChapter(client(legacy),old,old.manifest.chapters[0]));
assert.equal(old.manifest.chapters.length,1);
const prompt=core.newBookPrompt({repository:rootURL,platform:'七猫中文网',preferences:'测试偏好'});
assert.match(prompt,/V6\.0/);assert.match(prompt,/6\.0\.0/);assert.doesNotMatch(prompt,/release-check|reference_bridge|operator_recovery|4\.6\.4/);
const entry={title:'合成测试',repository_url:rootURL,book_id:book.state.book_id,expected_time:'09:00'};
assert.match(core.writingPrompt(entry),/不创建或修改定时日程/);
assert.match(core.writingPrompt(entry,'',{scheduled:true}),/唯一每日写作任务/);
assert.match(core.writingPrompt(entry),/同一天不限章数/);
assert.throws(()=>core.newBookPrompt({repository:'https://github.com/1464356758/xiaoshuoV5'}));
const broken=structuredClone(book.state);broken.chapters['1'].record_sha256='0'.repeat(64);
assert.throws(()=>v6.validateV6State(broken,book.manifest));
const rpath='book/'+book.state.chapters['1'].record_path;
const raw=await readFile(path.join(fixture,rpath),'utf8');
await writeFile(path.join(fixture,rpath),raw+' ');
await assert.rejects(()=>core.readFormalChapter(c,book,book.manifest.chapters[0]));
await writeFile(path.join(fixture,rpath),raw);
const worker=(await import(pathToFileURL(path.join(release,'worker.mjs')).href)).default;
const res=await worker.fetch(new Request('https://example.test/downloads/novel-init.zip'));
const bytes=new Uint8Array(await res.arrayBuffer());
const {createHash}=await import('node:crypto');
assert.equal(createHash('sha256').update(bytes).digest('hex'),res.headers.get('X-Content-SHA256'));
assert.deepEqual(bytes,new Uint8Array(await readFile(path.join(release,'初始化系统包.zip'))));
assert.equal((await worker.fetch(new Request('https://example.test/downloads/novel-init.zip',{method:'HEAD'}))).status,200);
assert.equal((await worker.fetch(new Request('https://example.test/downloads/novel-init.zip',{method:'POST'}))).status,405);
console.log('V6与旧版正文读取、冻结记录绑定、手动/定时指令、下载包一致性：PASS');
